// Electron wraps every main-process failure as "Error invoking remote method 'x': Error: …".
// People should only ever read the message itself.
const invoke = (channel, ...args) => ipcRenderer.invoke(channel, ...args).catch((error) => {
  throw new Error(String(error?.message || error).replace(/^Error invoking remote method '[^']+':\s*/, '').replace(/^(?:[A-Za-z]*Error):\s*/, ''));
});

